"""Write the Windows version resource PyInstaller embeds in the .exe files (Properties > Details).

    python ElementRemover/make_version_file.py ElementRemover/version_info.txt
    pyinstaller ... --version-file version_info.txt

Everything comes from element_remover/about.py: product, version, publisher, copyright.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from element_remover import about  # noqa: E402

TEMPLATE = """# UTF-8 -- generated by make_version_file.py from element_remover/about.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable(u'040904B0', [
      StringStruct(u'CompanyName', {company!r}),
      StringStruct(u'FileDescription', {product!r}),
      StringStruct(u'FileVersion', {version!r}),
      StringStruct(u'InternalName', {internal!r}),
      StringStruct(u'LegalCopyright', {copyright!r}),
      StringStruct(u'OriginalFilename', {original!r}),
      StringStruct(u'ProductName', {product!r}),
      StringStruct(u'ProductVersion', {version!r}),
      StringStruct(u'Comments', {comments!r})])]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


def version_tuple(v):
    nums = [int(x) for x in v.split(".")[:4] if x.isdigit()]
    return tuple((nums + [0, 0, 0, 0])[:4])


def render(exe_name):
    return TEMPLATE.format(nums=version_tuple(about.VERSION), company=about.PUBLISHER, product=about.PRODUCT,
                           version=about.VERSION, internal=os.path.splitext(exe_name)[0],
                           copyright=about.COPYRIGHT.replace(u"\u00a9", "(c)"),
                           original=exe_name, comments=about.WEBSITE)


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "version_info.txt"
    exe = sys.argv[2] if len(sys.argv) > 2 else about.PRODUCT + ".exe"
    with open(out, "w", encoding="utf-8") as f:
        f.write(render(exe))
    print("wrote %s for %s %s" % (out, about.PRODUCT, about.VERSION))
