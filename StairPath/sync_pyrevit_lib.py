"""Copy the engine files the pyRevit button shares with the exe into the shared Netbuild.extension's lib folder,
and regenerate stair_path/payload.py (the same engine as text, sent to Revit through the MCP listener).

    python StairPath/sync_pyrevit_lib.py

Run it after changing any of SHARED; the tests fail while the copies or the payload differ.
"""

import io
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "stair_path")
EXT = os.path.join(os.path.dirname(HERE), "LevelShifter", "pyRevit", "Netbuild.extension")   # the shared extension
DST = os.path.join(EXT, "lib", "stair_path")
SHARED = ["__init__.py", "about.py", "rules.py", "engine.py"]   # IronPython 2.7 + CPython 3
PAYLOAD = os.path.join(SRC, "payload.py")
ENGINE_IMPORTS = ["from . import rules\n", "from .rules import Check\n"]   # the payload binds these itself

HEADER = '''"""GENERATED by StairPath/sync_pyrevit_lib.py from rules.py and engine.py -- do not edit.

The command line sends this engine to Revit as text (revit.action_code): RULES runs as a module named
``rules``, ENGINE runs in the listener's namespace with ``rules`` and ``Check`` already bound.
"""

'''


def _read(name):
    with io.open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read()


def payload_source():
    rules_src, engine_src = _read("rules.py"), _read("engine.py")
    for line in ENGINE_IMPORTS:
        if engine_src.count(line) != 1:
            raise ValueError("engine.py must import exactly once: %r" % line)
        engine_src = engine_src.replace(line, "")
    for name, src in (("rules.py", rules_src), ("engine.py", engine_src)):
        if "'''" in src or "\\'" in src or not src.isascii():
            raise ValueError("%s cannot be embedded: keep it ASCII, without ''' or \\'" % name)
    return HEADER + "RULES = r'''" + rules_src + "'''\n\nENGINE = r'''" + engine_src + "'''\n"


if __name__ == "__main__":
    if not os.path.isdir(DST):
        os.makedirs(DST)
    for name in SHARED:
        shutil.copyfile(os.path.join(SRC, name), os.path.join(DST, name))
        print("copied %s" % name)
    with io.open(PAYLOAD, "w", encoding="utf-8", newline="\n") as f:
        f.write(payload_source())
    print("wrote %s" % os.path.relpath(PAYLOAD, HERE))
